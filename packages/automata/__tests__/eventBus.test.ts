import { randomInteger, randomString, uniqId } from '@yantrix/utils';
import { beforeEach, describe, expect, it, vitest } from 'vitest';
import { BasicEventBus, createEventBus, STACK_PROCESSING_BATCH_SIZE, TAutomataEventMetaType, TAutomataEventStack } from '../src';
import { AbstractBaseClass } from '../src/mixins/BaseClass.js';
import { TTestEvent, TTestEventMeta } from './fixtures';

class EventBusTest extends createEventBus<
	TTestEvent,
	TTestEventMeta<TTestEvent>
>()(AbstractBaseClass) {}

const FrameRate = Math.ceil(1000 / 60);

describe('eventBus', () => {
	let sampleInstance: EventBusTest = new EventBusTest();
	let sampleEventMeta: TAutomataEventMetaType<TTestEvent, TTestEventMeta<TTestEvent>>;
	const sampleHandler = vitest.fn((event: typeof sampleEventMeta) => ({
		...event,
		task_id: uniqId(),
		result: Promise.resolve([]),
	}));
	beforeEach(() => {
		vitest.restoreAllMocks();
		vitest.clearAllTimers();
		sampleInstance = new EventBusTest();
		sampleEventMeta = {
			event: randomInteger(1000, 2000),
			meta: {
				meta: randomString(10),
			},
		};
	});
	describe('constructor', () => {
		it('returns an instance of EventBusTest', () => {
			expect(sampleInstance).toBeInstanceOf(EventBusTest);
		});
		it('returns an instance of AbstractBaseClass', () => {
			expect(sampleInstance).toBeInstanceOf(AbstractBaseClass);
		});
		it('has an autogenerated alphanumeric Correlation ID', () => {
			expect(sampleInstance)
				.property('correlationId')
				.to
				.match(/^[A-Z0-9]+$/);
		});
		it('is empty by default', () => {
			expect(sampleInstance.getEventStack()).toEqual([]);
		});
	});

	describe('delivery order', () => {
		function recordDelivery(bus: BasicEventBus, ids: number[]): number[] {
			const seen: number[] = [];
			for (const id of ids) {
				bus.subscribe(id, (event) => {
					seen.push(id);
					return { ...event, task_id: String(id), result: null };
				});
			}
			return seen;
		}

		it.each([
			[undefined, [1, 2, 3]],
			['fifo', [1, 2, 3]],
			['lifo', [3, 2, 1]],
		] as const)('delivers buffered events in %s order', async (order, expected) => {
			const bus = new BasicEventBus(order);
			const seen = recordDelivery(bus, [1, 2, 3]);
			const buffered = [1, 2, 3].map(event => ({ event, meta: null }));
			bus.pause().dispatch(...buffered);
			expect(bus.getEventStack()).toEqual(buffered);
			bus.resume();
			await bus.whenIdle();
			expect(seen).toEqual(expected);
		});

		it.each([
			['fifo', [2, 3, 4]],
			['lifo', [4, 3, 2]],
		] as const)('applies %s to async follow-ups alongside already queued events', async (order, expected) => {
			const bus = new BasicEventBus(order);
			const seen = recordDelivery(bus, [2, 3, 4]);
			bus.subscribe(1, event => ({
				...event,
				task_id: 'source',
				result: Promise.resolve([{ event: 3, meta: null }, { event: 4, meta: null }]),
			}));
			bus.dispatch({ event: 1, meta: null });
			bus.dispatch({ event: 2, meta: null });
			await bus.whenIdle();
			expect(seen).toEqual(expected);
		});

		it('retains LIFO order for remaining events after a subscriber throws', async () => {
			const bus = new BasicEventBus('lifo');
			const seen = recordDelivery(bus, [1, 2, 3]);
			bus.subscribe(3, () => {
				throw new Error('subscriber failed');
			});
			bus.pause().dispatch(...[1, 2, 3].map(event => ({ event, meta: null })));
			const waiting = bus.whenIdle();
			expect(() => bus.resume()).toThrow('subscriber failed');
			await expect(waiting).rejects.toThrow('subscriber failed');
			expect(seen).toEqual([3, 2, 1]);
		});

		it('rejects an unknown order at construction', () => {
			// @ts-expect-error JavaScript consumers can pass an unsupported order.
			expect(() => new BasicEventBus('random')).toThrow(/order/);
		});

		it.each(['fifo', 'lifo'] as const)('drains a multi-batch %s buffer when subscribers return empty tasks', async (order) => {
			const bus = new BasicEventBus(order);
			const seen: number[] = [];
			const buffer = Array.from({ length: STACK_PROCESSING_BATCH_SIZE + 10 }, (_, index) => index + 1);
			bus.subscribe(1, (input) => {
				seen.push(input.meta.index);
				return { ...input, task_id: 'work', result: Promise.resolve([]) };
			});
			bus.pause().dispatch(...buffer.map(meta => ({ event: 1, meta: { index: meta } })));
			bus.resume();
			await bus.whenIdle();
			expect(seen).toEqual(order === 'fifo' ? buffer : buffer.reverse());
			expect(bus.getEventStack()).toEqual([]);
		});

		it('allows one wide fan-out and rejects repeatedly multiplying follow-ups of the same event', async () => {
			const bus = new BasicEventBus();
			const count = STACK_PROCESSING_BATCH_SIZE * 3;
			const children = Array.from({ length: count }, () => ({ event: 2, meta: null }));
			bus.subscribe(1, input => ({ ...input, task_id: 'start', result: Promise.resolve(children) }));
			const received = recordDelivery(bus, [2]);
			bus.dispatch({ event: 1, meta: null });
			await bus.whenIdle();
			expect(received).toHaveLength(count);

			let calls = 0;
			bus.subscribe(3, (input) => {
				// Keep a broken guard bounded during regression testing.
				const result = calls++ < 200 ? [input, input] : [];
				return { ...input, task_id: 'multiply', result: Promise.resolve(result) };
			});
			bus.dispatch({ event: 3, meta: null });
			await expect(bus.whenIdle()).rejects.toThrow('Stack is growing too fast');
			expect(calls).toBeLessThan(200);
			bus.dispatch({ event: 2, meta: null });
			await bus.whenIdle();
			expect(received).toHaveLength(count + 1);
		});
	});

	describe('/subscribe', () => {
		it('returns self', () => {
			expect(sampleInstance.subscribe(sampleEventMeta.event!, sampleHandler)).toBe(sampleInstance);
		});
		it('throws when provided invalid event', () => {
			expect(() => sampleInstance.subscribe(null as any, sampleHandler)).toThrow();
			expect(() => sampleInstance.subscribe(-5, sampleHandler)).toThrow();
		});
		it('throws when provided invalid handler', () => {
			expect(() => sampleInstance.subscribe(sampleEventMeta.event!, null as any)).toThrow();
			expect(() => sampleInstance.subscribe(sampleEventMeta.event!, {} as any)).toThrow();
			expect(() => sampleInstance.subscribe(sampleEventMeta.event!, 'not a function' as any)).toThrow();
		});
		it('when the same handler added twice, it\'s called only once', () => {
			const mockHandler = vitest.fn();
			sampleInstance.subscribe(sampleEventMeta.event!, mockHandler);
			sampleInstance.subscribe(sampleEventMeta.event!, mockHandler);
			sampleInstance.dispatch(sampleEventMeta);
			expect(mockHandler).toHaveBeenCalledTimes(1);
		});
		it('when handler returns result:null, events are processed synchronously', async () => {
			const sampleEventMeta1 = {
				event: randomInteger(1, 100),
				meta: {
					meta: randomString(10),
				},
			};
			const sampleEventMeta2 = {
				event: randomInteger(1, 100),
				meta: {
					meta: randomString(10),
				},
			};
			const mockHandler = vitest.fn((event: typeof sampleEventMeta) => ({
				...event,
				task_id: uniqId(),
				result: null,
			}));
			sampleInstance
				.subscribe(sampleEventMeta1.event!, mockHandler)
				.subscribe(sampleEventMeta2.event!, mockHandler)
				.dispatch(sampleEventMeta1)
				.dispatch(sampleEventMeta2);
			expect(mockHandler).toHaveBeenCalledTimes(2);
		});
		it('when handler returns result as Promise, it gets into queue', async () => {
			const sampleEventMeta1 = {
				event: randomInteger(1, 100),
				meta: {
					meta: randomString(10),
				},
			};
			const sampleEventMeta2 = {
				event: randomInteger(101, 200),
				meta: {
					meta: randomString(10),
				},
			};
			const mockHandler = vitest.fn((event: typeof sampleEventMeta) => ({
				...event,
				task_id: uniqId(),
				result: new Promise<TAutomataEventStack<TTestEvent, TTestEventMeta<TTestEvent>>>((resolve) => {
					setTimeout(() => {
						resolve([sampleEventMeta2]);
					}, FrameRate);
				}),
			}));
			sampleInstance
				.clearEventStack()
				.subscribe(sampleEventMeta1.event!, mockHandler)
				.dispatch(sampleEventMeta1);
			await new Promise(resolve => setTimeout(resolve, FrameRate * 2));
			expect(mockHandler).toHaveBeenCalledTimes(1);
			expect(sampleInstance.getEventStack()).toHaveLength(0);
		});
		it('when handler returns result as Promise, pausing and resuming after dispatching works as expected', async () => {
			const sampleEventMeta1 = {
				event: randomInteger(1, 100),
				meta: {
					meta: randomString(10),
				},
			};
			const sampleEventMeta2 = {
				event: randomInteger(101, 200),
				meta: {
					meta: randomString(10),
				},
			};
			const mockHandler1 = vitest.fn((event: typeof sampleEventMeta) => ({
				...event,
				task_id: uniqId(),
				result: new Promise<TAutomataEventStack<TTestEvent, TTestEventMeta<TTestEvent>>>((resolve) => {
					setTimeout(() => {
						resolve([sampleEventMeta2]);
					}, FrameRate);
				}),
			}));
			const mockHandler2 = vitest.fn((event: typeof sampleEventMeta) => ({
				...event,
				task_id: uniqId(),
				result: null,
			}));
			sampleInstance
				.clearEventStack()
				.subscribe(sampleEventMeta1.event!, mockHandler1)
				.subscribe(sampleEventMeta2.event!, mockHandler2)
				.dispatch(sampleEventMeta1)
				.pause();
			await new Promise(resolve => setTimeout(resolve, FrameRate * 2));
			expect(mockHandler1).toHaveBeenCalledTimes(1);
			expect(mockHandler2).not.toHaveBeenCalled();
			expect(sampleInstance.getEventStack()).toHaveLength(1);
			sampleInstance.resume();
			await new Promise(resolve => setTimeout(resolve, FrameRate));
			expect(mockHandler2).toHaveBeenCalledTimes(1);
			expect(sampleInstance.getEventStack()).toHaveLength(0);
		});
		it('all events returned by handlers are added to the queue as one batch during processing cycle', async () => {
			const sampleEventMeta1 = {
				event: randomInteger(1, 10),
				meta: {
					meta: randomString(10),
				},
			};
			const sampleEventMeta2 = {
				event: randomInteger(11, 20),
				meta: {
					meta: randomString(10),
				},
			};
			const sampleEventMeta3 = {
				event: randomInteger(21, 30),
				meta: {
					meta: randomString(10),
				},
			};
			const sampleEventMeta4 = {
				event: randomInteger(31, 40),
				meta: {
					meta: randomString(10),
				},
			};
			const mockHandler1 = vitest.fn((event: typeof sampleEventMeta) => ({
				...event,
				task_id: uniqId(),
				result: new Promise<TAutomataEventStack<TTestEvent, TTestEventMeta<TTestEvent>>>((resolve) => {
					setTimeout(() => {
						resolve([sampleEventMeta2]);
					}, FrameRate);
				}),
			}));
			const mockHandler2 = vitest.fn((event: typeof sampleEventMeta) => ({
				...event,
				task_id: uniqId(),
				result: new Promise<TAutomataEventStack<TTestEvent, TTestEventMeta<TTestEvent>>>((resolve) => {
					setTimeout(() => {
						resolve([sampleEventMeta4]);
					}, FrameRate * 3);
				}),
			}));
			sampleInstance
				.clearEventStack()
				.subscribe(sampleEventMeta1.event!, mockHandler1)
				.subscribe(sampleEventMeta3.event!, mockHandler2)
				.dispatch(sampleEventMeta1, sampleEventMeta3)
				.pause();

			// by this time the first handler resolves, but since both originating events were dispatched as a batch,
			// it still waits for the second handler
			await new Promise(resolve => setTimeout(resolve, FrameRate * 2));
			expect(mockHandler1).toHaveBeenCalledTimes(1);
			expect(mockHandler2).toHaveBeenCalledTimes(1);
			expect(sampleInstance.getEventStack()).toHaveLength(0);
			// now the second handler resolves, so both events are added to the queue, and since it's paused, they are not processed
			await new Promise(resolve => setTimeout(resolve, FrameRate * 3));
			expect(mockHandler1).toHaveBeenCalledTimes(1);
			expect(mockHandler2).toHaveBeenCalledTimes(1);
			expect(sampleInstance.getEventStack()).toHaveLength(2);
			expect(sampleInstance.getEventStack()).toEqual([sampleEventMeta2, sampleEventMeta4]);
		});
	});
	describe('/unsubscribe', () => {
		it('throws when provided invalid event', () => {
			expect(() => sampleInstance.unsubscribe(null as any, sampleHandler)).toThrow();
			expect(() => sampleInstance.unsubscribe(-5, sampleHandler)).toThrow();
		});
		it('removes a specific handler', () => {
			const mockHandler1 = vitest.fn();
			const mockHandler2 = vitest.fn();
			sampleInstance.subscribe(sampleEventMeta.event!, mockHandler1);
			sampleInstance.subscribe(sampleEventMeta.event!, mockHandler2);
			sampleInstance.unsubscribe(sampleEventMeta.event!, mockHandler1);
			sampleInstance.dispatch(sampleEventMeta);
			expect(mockHandler1).not.toHaveBeenCalled();
			expect(mockHandler2).toHaveBeenCalledTimes(1);
		});
		it('ignores non-existent handler', () => {
			sampleInstance.unsubscribe(sampleEventMeta.event!, sampleHandler);
			expect(() => sampleInstance.unsubscribe(sampleEventMeta.event!, sampleHandler)).not.toThrow();
		});
		it('removes all handlers for given event if passed null', () => {
			const mockHandler1 = vitest.fn();
			const mockHandler2 = vitest.fn();
			sampleInstance.subscribe(sampleEventMeta.event!, mockHandler1);
			sampleInstance.subscribe(sampleEventMeta.event!, mockHandler2);
			sampleInstance.unsubscribe(sampleEventMeta.event!, null);
			sampleInstance.dispatch(sampleEventMeta);
			expect(mockHandler1).not.toHaveBeenCalled();
			expect(mockHandler2).not.toHaveBeenCalled();
		});
	});
	describe('/resume, /pause', () => {
		it('affects isRunning status', () => {
			sampleInstance.resume();
			expect(sampleInstance.isRunning()).toBe(true);
			sampleInstance.pause();
			expect(sampleInstance.isRunning()).toBe(false);
			sampleInstance.resume();
			expect(sampleInstance.isRunning()).toBe(true);
		});
		it('/resume consumes all events in queue', () => {
			sampleInstance
				.subscribe(sampleEventMeta.event!, sampleHandler)
				.pause()
				.dispatch(sampleEventMeta, { event: randomInteger(), meta: null });

			expect(sampleInstance.getEventStack().length).toBe(2);
			expect(sampleHandler).not.toHaveBeenCalled();

			sampleInstance.resume();

			expect(sampleInstance.getEventStack().length).toBe(0);
			expect(sampleHandler).toHaveBeenCalledWith(sampleEventMeta);
		});
	});
	describe('/getEventStack', () => {
		it('events are added to event stack', () => {
			sampleInstance.subscribe(sampleEventMeta.event!, sampleHandler).pause();
			expect(sampleInstance.getEventStack().length).toBe(0);
			sampleInstance.dispatch(sampleEventMeta);
			expect(sampleInstance.getEventStack().length).toBe(1);
		});
		it('event stack can be cleared', () => {
			sampleInstance.pause();

			sampleInstance.dispatch(sampleEventMeta);
			expect(sampleInstance.getEventStack().length).toBe(1);

			sampleInstance.clearEventStack();

			expect(sampleInstance.getEventStack().length).toBe(0);
		});
	});
	describe('/dispatch', () => {
		it('can process events synchronously', () => {
			sampleInstance
				.subscribe(sampleEventMeta.event!, sampleHandler)
				.dispatch(sampleEventMeta);
			expect(sampleInstance.getEventStack().length).toBe(0);
			expect(sampleHandler).toBeCalledWith(sampleEventMeta);
		});
		it('does not process events if paused', () => {
			sampleInstance
				.subscribe(sampleEventMeta.event!, sampleHandler)
				.pause()
				.dispatch(sampleEventMeta);

			expect(sampleInstance.getEventStack().length).toBe(1);
			expect(sampleHandler).not.toHaveBeenCalled();
		});
		it('there is no race condition when events are dispatched both directly and from handler', async () => {
			const sampleEventMeta1 = {
				event: randomInteger(1, 100),
				meta: {
					meta: randomString(10),
				},
			};
			const sampleEventMeta2 = {
				event: randomInteger(101, 200),
				meta: {
					meta: randomString(10),
				},
			};
			const mockHandler1 = vitest.fn((event: typeof sampleEventMeta) => ({
				...event,
				task_id: uniqId(),
				result: new Promise<TAutomataEventStack<TTestEvent, TTestEventMeta<TTestEvent>>>((resolve) => {
					setTimeout(() => {
						resolve([sampleEventMeta2]);
					}, FrameRate);
				}),
			}));
			const mockHandler2 = vitest.fn((event: typeof sampleEventMeta) => ({
				...event,
				task_id: uniqId(),
				result: new Promise<TAutomataEventStack<TTestEvent, TTestEventMeta<TTestEvent>>>((resolve) => {
					setTimeout(() => {
						resolve([]);
					}, 3 * FrameRate);
				}),
			}));
			sampleInstance
				.clearEventStack()
				.subscribe(sampleEventMeta1.event!, mockHandler1)
				.subscribe(sampleEventMeta2.event!, mockHandler2)
				.dispatch(sampleEventMeta1, sampleEventMeta2);
			// so, event#1 resolves at point 1,  event#2 does  at point 3
			// dispatching another event #3 at point 2 should add new event to queue without processing it,
			// and it's gonna be processed in order #1 - #3 - #2
			expect(mockHandler1).toHaveBeenCalledTimes(1);
			expect(mockHandler2).toHaveBeenCalledTimes(1);
			await new Promise(resolve => setTimeout(resolve, FrameRate * 2));
			expect(sampleInstance.getEventStack()).toHaveLength(0);
			sampleInstance.dispatch(sampleEventMeta);
			expect(sampleInstance.getEventStack()).toHaveLength(1);
			expect(sampleInstance.getEventStack()).toEqual([sampleEventMeta]);
			sampleInstance.pause();
			await new Promise(resolve => setTimeout(resolve, FrameRate)); // now at point 3
			expect(sampleInstance.getEventStack()).toHaveLength(2);
			expect(sampleInstance.getEventStack()).toEqual([sampleEventMeta, sampleEventMeta2]);
			await new Promise(resolve => setTimeout(resolve, FrameRate)); // now at point 4
			sampleInstance.resume();
			expect(sampleInstance.getEventStack()).toHaveLength(0);
			expect(mockHandler2).toHaveBeenCalledTimes(2);
		});
	});
	describe('/whenIdle', () => {
		it('rejects waiting callers on a synchronous subscriber error and drains remaining events', async () => {
			const failure = new Error('subscriber failed');
			const seen: string[] = [];
			sampleInstance.subscribe(1, () => {
				throw failure;
			});
			sampleInstance.subscribe(2, (event) => {
				seen.push(event.meta!.meta);
				return { ...event, task_id: uniqId(), result: null };
			});
			sampleInstance.pause().dispatch(
				{ event: 1, meta: { meta: 'fails' } },
				{ event: 2, meta: { meta: 'already queued' } },
			);
			const waiting = sampleInstance.whenIdle();
			expect(() => sampleInstance.resume()).toThrow(failure);
			await expect(waiting).rejects.toBe(failure);
			expect(seen).toEqual(['already queued']);

			sampleInstance.dispatch({ event: 2, meta: { meta: 'later dispatch' } });
			await sampleInstance.whenIdle();
			expect(seen).toEqual(['already queued', 'later dispatch']);
		});

		it('reports an asynchronous task failure to all observers and recovers for the next drain', async () => {
			const failure = new Error('task failed');
			let failTask!: (reason: Error) => void;
			sampleInstance.subscribe(1, event => ({
				...event,
				task_id: uniqId(),
				result: new Promise((_resolve, reject) => { failTask = reject; }),
			}));
			const seen: string[] = [];
			sampleInstance.subscribe(2, (event) => {
				seen.push(event.meta!.meta);
				return { ...event, task_id: uniqId(), result: null };
			});
			sampleInstance.dispatch({ event: 1, meta: null });
			const observer1 = sampleInstance.whenIdle();
			sampleInstance.dispatch({ event: 2, meta: { meta: 'first' } }, { event: 2, meta: { meta: 'second' } });
			const observer2 = sampleInstance.whenIdle();
			failTask(failure);
			await Promise.all([expect(observer1).rejects.toBe(failure), expect(observer2).rejects.toBe(failure)]);
			expect(seen).toEqual(['first', 'second']);
			await expect(sampleInstance.whenIdle()).rejects.toBe(failure);

			sampleInstance.dispatch({ event: 2, meta: { meta: 'third' } });
			await sampleInstance.whenIdle();
			expect(seen).toEqual(['first', 'second', 'third']);
		});

		it('reports invalid async follow-up events without preventing later dispatch', async () => {
			sampleInstance.subscribe(1, event => ({
				...event,
				task_id: uniqId(),
				result: Promise.resolve([{ event: -1, meta: null }]),
			}));
			sampleInstance.dispatch({ event: 1, meta: null });
			await expect(sampleInstance.whenIdle()).rejects.toThrow('Invalid event received from promise');
			sampleInstance.dispatch({ event: 2, meta: null });
			await sampleInstance.whenIdle();
		});

		it('waits for tasks already started when another subscriber throws in the same batch', async () => {
			const failure = new Error('second subscriber failed');
			let finishTask!: (events: TAutomataEventStack<TTestEvent, TTestEventMeta<TTestEvent>>) => void;
			const pendingTask = new Promise<TAutomataEventStack<TTestEvent, TTestEventMeta<TTestEvent>>>((resolve) => {
				finishTask = resolve;
			});
			sampleInstance.subscribe(1, event => ({ ...event, task_id: uniqId(), result: pendingTask }));
			sampleInstance.subscribe(1, () => {
				throw failure;
			});
			const followup = vitest.fn();
			sampleInstance.subscribe(2, followup);
			expect(() => sampleInstance.dispatch({ event: 1, meta: null })).toThrow(failure);
			const onFailure = vitest.fn();
			const idle = sampleInstance.whenIdle().catch(onFailure);
			await Promise.resolve();
			expect(onFailure).not.toHaveBeenCalled();
			finishTask([{ event: 2, meta: { meta: 'from the failed batch' } }]);
			await idle;
			expect(onFailure).toHaveBeenCalledWith(failure);
			expect(followup).not.toHaveBeenCalled();
		});

		it('resolves after asynchronous follow-up Events are fully drained', async () => {
			const firstEvent = randomInteger(1, 100);
			const secondEvent = randomInteger(101, 200);
			const seen: number[] = [];
			sampleInstance.subscribe(firstEvent, event => ({
				...event,
				task_id: uniqId(),
				result: Promise.resolve([{ event: secondEvent, meta: { meta: 'follow-up' } }]),
			}));
			sampleInstance.subscribe(secondEvent, (event) => {
				seen.push(secondEvent);
				return { ...event, task_id: uniqId(), result: null };
			});

			sampleInstance.dispatch({ event: firstEvent, meta: { meta: 'initial' } });
			await sampleInstance.whenIdle();

			expect(seen).toEqual([secondEvent]);
			expect(sampleInstance.getEventStack()).toEqual([]);
		});

		it('drains synchronous queues larger than the processing batch size', async () => {
			const event = randomInteger(1, 100);
			const handler = vitest.fn(raw => ({ ...raw, task_id: uniqId(), result: null }));
			const events = Array.from({ length: 40 }, () => ({ event, meta: { meta: 'batch' } }));
			sampleInstance
				.subscribe(event, handler)
				.pause()
				.dispatch(...events)
				.resume();

			await sampleInstance.whenIdle();

			expect(handler).toHaveBeenCalledTimes(40);
			expect(sampleInstance.getEventStack()).toEqual([]);
		});
	});
});
